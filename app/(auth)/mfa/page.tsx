'use client';

import * as React from 'react';
import { useRouter } from 'next/navigation';
import { verifyMfaChallengeAction } from '@/server/actions/auth.actions';
import { Button } from '@/components/ui/button';
import { Input } from '@/components/ui/input';
import { Banner } from '@/components/ui/feedback';
import { createClient } from '@/lib/supabase/client';

export default function MfaChallengePage() {
  const router = useRouter();
  const [code, setCode] = React.useState('');
  const [factorId, setFactorId] = React.useState<string | null>(null);
  const [errorMsg, setErrorMsg] = React.useState<string | null>(null);
  const [isLoading, setIsLoading] = React.useState(false);

  React.useEffect(() => {
    async function loadFactors() {
      const supabase = createClient();
      const { data: factors } = await supabase.auth.mfa.listFactors();
      if (factors?.totp && factors.totp.length > 0) {
        setFactorId(factors.totp[0].id);
      } else {
        router.push('/mfa/enroll');
      }
    }
    loadFactors();
  }, [router]);

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!factorId) return;

    setErrorMsg(null);
    setIsLoading(true);

    try {
      const res = await verifyMfaChallengeAction(factorId, { code });
      if (res.error) {
        setErrorMsg(res.error.message);
        setIsLoading(false);
        return;
      }

      if (res.data?.redirectTo) {
        router.push(res.data.redirectTo);
      }
    } catch {
      setErrorMsg('Failed to verify security code. Please try again.');
      setIsLoading(false);
    }
  };

  return (
    <div className="space-y-6">
      <div className="space-y-1">
        <h2 className="text-xl font-semibold text-on-surface">Two-Factor Authentication</h2>
        <p className="text-sm text-on-surface-variant">
          Enter the 6-digit security code generated by your authenticator app.
        </p>
      </div>

      {errorMsg && (
        <Banner variant="error" title="Verification Failed">
          {errorMsg}
        </Banner>
      )}

      <form onSubmit={handleSubmit} className="space-y-4">
        <div className="space-y-1.5">
          <label className="text-xs font-medium uppercase tracking-wider text-outline" htmlFor="totp-code">
            6-Digit Authenticator Code
          </label>
          <Input
            id="totp-code"
            type="text"
            required
            maxLength={6}
            autoFocus
            pattern="\d{6}"
            placeholder="123456"
            className="text-center font-mono text-2xl tracking-widest h-12"
            value={code}
            onChange={(e) => setCode(e.target.value.replace(/\D/g, ''))}
          />
        </div>

        <Button
          type="submit"
          className="w-full"
          disabled={isLoading || code.length !== 6 || !factorId}
        >
          {isLoading ? 'Verifying Code...' : 'Verify & Continue'}
        </Button>
      </form>

      <div className="pt-4 border-t border-outline-variant/40 text-center">
        <p className="text-xs text-outline">
          Lost access to your authenticator? Contact your System Administrator to reset your multi-factor security.
        </p>
      </div>
    </div>
  );
}
